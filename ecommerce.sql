Use dbms_finals;

DROP TABLE IF EXISTS Audit_Log;
DROP TABLE IF EXISTS Shipments;
DROP TABLE IF EXISTS Order_Items;
DROP TABLE IF EXISTS Orders;
DROP TABLE IF EXISTS Products;
DROP TABLE IF EXISTS Sellers;
DROP TABLE IF EXISTS Customers;


CREATE TABLE Customers (
	customer_id INT AUTO_INCREMENT PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    email VARCHAR(50) NOT NULL UNIQUE,
    house_number INT NOT NULL,
    street VARCHAR(50) NOT NULL,
    barangay INT NOT NULL,
    city VARCHAR(50) NOT NULL,
    province VARCHAR(50) NOT NULL,
    postal_code INT NOT NULL
);

CREATE TABLE Sellers (
	seller_id INT AUTO_INCREMENT PRIMARY KEY,
    shop_name VARCHAR(100) NOT NULL UNIQUE,
    owner_firstName VARCHAR(50) NOT NULL,
    owner_lastName VARCHAR(50) NOT NULL,
    email VARCHAR(50) NOT NULL UNIQUE,
    house_number INT NOT NULL,
    street VARCHAR(50) NOT NULL,
    barangay INT NOT NULL,
    city VARCHAR(50) NOT NULL,
    province VARCHAR(50) NOT NULL,
    postal_code INT NOT NULL
);

CREATE TABLE Products (
	Product_id INT AUTO_INCREMENT PRIMARY KEY,
    seller_id INT NOT NULL,
    sku VARCHAR(50) NOT NULL UNIQUE,
    category VARCHAR(50) NOT NULL,
    product_name VARCHAR(50) NOT NULL,
    unit_price DECIMAL(10,2) NOT NULL CHECK (unit_price >= 0.00),
    stock_quantity INT NOT NULL CHECK (stock_quantity >= 0),
    is_available BOOLEAN DEFAULT FALSE,
    CONSTRAINT fk_products_seller FOREIGN KEY(seller_id)
		REFERENCES Sellers(seller_id) ON DELETE CASCADE
);

CREATE TABLE Orders (
    order_id INT AUTO_INCREMENT PRIMARY KEY,
    customer_id INT NOT NULL,
    order_date DATE NOT NULL,
    payment_method ENUM('COD', 'GCASH', 'BANK') NOT NULL,
    shipping_fee DECIMAL(8,2) NOT NULL CHECK (shipping_fee >= 0.0),
    order_status VARCHAR(30) NOT NULL CHECK (order_status IN ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled')),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES Customers(customer_id) ON DELETE CASCADE
);

CREATE TABLE Order_Items (
	order_items_id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity INT NOT NULL CHECK (quantity >= 0),
    unit_price DECIMAL(10,2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT fk_oder_items_order FOREIGN KEY(order_id)
		REFERENCES Orders(order_id) ON DELETE CASCADE,
	CONSTRAINT fk_order_items_products FOREIGN KEY (product_id)
		REFERENCES Products(product_id) ON DELETE CASCADE
);

CREATE TABLE Shipments (
    shipment_id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,
    courier_partner ENUM('J&T Express', 'Flash Express', 'LBC Express', 'SPX Express') NOT NULL,
    tracking_number VARCHAR(50) NOT NULL UNIQUE,
    shipped_date DATETIME NOT NULL,
    delivery_date DATETIME NOT NULL,
    delivery_status VARCHAR(50) NOT NULL,
    CONSTRAINT fk_shipments_order FOREIGN KEY (order_id)
        REFERENCES Orders(order_id) ON DELETE CASCADE
);
    
CREATE TABLE Audit_Log (
	log_id INT AUTO_INCREMENT PRIMARY KEY,
    order_id INT NOT NULL,
    seller_id INT NOT NULL,
    record_id INT NOT NULL UNIQUE,
    action_type ENUM ('INSERT', 'UPDATE', 'DELETE') NOT NULL,
    old_value VARCHAR(300) NOT NULL,
    new_value VARCHAR(500) NOT NULL,
    changed_at DATETIME NOT NULL,
    CONSTRAINT fk_log_order FOREIGN KEY(order_id)
		REFERENCES Orders(order_id) ON DELETE CASCADE,
	CONSTRAINT fk_log_seller FOREIGN KEY(seller_id)
		REFERENCES Sellers(seller_id) ON DELETE CASCADE
);


